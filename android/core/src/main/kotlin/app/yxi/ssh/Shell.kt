package app.yxi.ssh

/**
 * 拼远端 shell 命令时**唯一**的转义与白名单。
 *
 * ⚠️ **为什么要有这么一个文件**：2026-09-04 的安全审计发现同一个转义函数在四个地方各抄了一份
 * （`ConfigRemote.shq` / `Dirs.q` / `Connect.shq`）——
 * 抄了四份的结果是**谁想起来谁用**，26 个插值点漏网。其中最要命的一条：
 * 会话名从服务器的 `~/.yxi/events.jsonl` 一路流进 `tmux capture-pane -t '…'`，
 * 而那个文件**服务器上的 agent 自己就能写**。被提示词注入打中的 agent 因此可以反过来
 * 驱使手机在服务器上执行未经审批的命令 —— 把「人在手机上把关」这个产品的全部意义绕开。
 *
 * 所以：**要往远端命令里塞变量，只用这里的两个函数。**
 */
object Shell {

    /** 单引号包起来。里面的单引号按 `'\''` 断开重接 —— POSIX shell 的标准写法。 */
    fun q(s: String): String = "'" + s.replace("'", "'\\''") + "'"

    /**
     * 会话名的**危险字符黑名单**。在信任边界上过一遍（解析 tmux 列表、解析事件流），
     * 不匹配的整条丢掉 —— fail-closed。
     *
     * ⚠️ 这是第二道防线，不是第一道：第一道是所有插值点都用 [q]。
     * 两道都要有 —— 第一道防「我漏了一个点」，第二道防「以后有人新加一个点又忘了」。
     *
     * ⚠️ **原来这里写的是 ASCII 白名单 `^[A-Za-z0-9._@%+=,:-]+$`，那是错的。**
     * 2026-09-04 的 E2E 当场撞见：用户机器上 30 个会话，App 只显示 22 ——
     * `cc-今天` `cc-日常对话` `cc-智商题` 这 8 个中文名会话被白名单**静默吃掉**了。
     * 会话名是用户自己起的，中文、空格、别的语言都天经地义。
     *
     * 所以判据改成「**这个名字当 shell 参数会不会跑出命令来**」：
     * 引号 / 反引号 / `$` / `;` / `&` / `|` / 重定向 / 反斜杠 / 控制字符 —— 这些才是能执行命令的，
     * 其余（中日韩、空格、括号）配上 [q] 完全无害。`/` 也挡掉：这个函数还被
     * [app.yxi.agent.Attachments] 拿去拼远端路径，放行 `/` 或 `..` 就是目录穿越。
     */
    private val BAD = "'\"`$;&|<>\\/\u0000".toSet()

    fun safeName(s: String): Boolean =
        s.isNotEmpty() && s.length <= 64 && s.trim('.').isNotEmpty() &&
            s.none { it.isISOControl() || it in BAD }

    /**
     * 路径白名单：给附件目录这类「用会话名拼出来的路径」用。
     * 允许 `/`，但**禁掉 `..`** —— 否则 `cc-x/../../..` 能跳出暂存区往任意目录投文件。
     */
    fun safePath(s: String): Boolean =
        s.isNotEmpty() && s.length <= 512 && !s.contains("..") && s.none { it.isISOControl() } &&
            s.none { it in "'\"`$;&|<>*?()[]{}\n\r" }
}
